const tables: Record<Locale, Record<Key, string>> = { en, "zh-CN": zh };

export function parseLocale(tag: string | undefined | null): Locale {
  return tag && /^zh(?!.*(hant|-tw|-hk|-mo))/i.test(tag) ? "zh-CN" : "en";
}

export function translate(locale: Locale, key: Key, args: Record<string, string | number> = {}): string {
  const text = tables[locale][key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(args[name] ?? `{${name}}`));
}

